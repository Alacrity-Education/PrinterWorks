#!/usr/bin/env python3
"""Generate the assembler's copy of the chase-budget constants.

sdasstm8 has no -D, so the two build-time chase constants reach
decode_asm.s through a GENERATED include instead.  The Makefile is the
SINGLE source: `make A_MAX=16 T_MAX=192` sets both the -D flags handed to
decode.c and the symbols written here, so the C and the assembly can
never disagree.

  gen_chase_cfg.py <A_MAX> <T_MAX> <outfile>

Only rewrites the file when the content changes, so an unchanged
parameter point never re-triggers an assembly.

Range rules (also asserted in decode.c and checked by guard_prod.py):
  A_MAX  2..255   candidate-list capacity AND the R7 admission cap.
                  Worst-case chase trials are A_MAX*(A_MAX+1)/2, which
                  must stay <= 255 for dec_info.trials (u8) -> A_MAX <= 22.
  T_MAX  1..255   residual comparisons.  ch_comps is a u8 in BOTH
                  decode.c and decode_asm.s (z_comps, 1 byte), and
                  dec_info.comps is a u8 report field, so T_MAX > 255
                  would need a 16-bit counter in the assembly -- a
                  separate change, deliberately not made.
"""
import sys
from pathlib import Path

BANNER = "; GENERATED by gen_chase_cfg.py -- do not edit, do not commit.\n"


def main(amax, tmax, out):
    if not 2 <= amax <= 255:
        raise SystemExit("gen_chase_cfg: A_MAX %d outside 2..255" % amax)
    if amax * (amax + 1) // 2 > 255:
        raise SystemExit(
            "gen_chase_cfg: A_MAX %d gives %d worst-case trials, and "
            "dec_info.trials is a u8 (max A_MAX = 22)"
            % (amax, amax * (amax + 1) // 2))
    if not 1 <= tmax <= 255:
        raise SystemExit(
            "gen_chase_cfg: T_MAX %d outside 1..255 -- ch_comps is a u8 "
            "in decode.c, decode_asm.s (z_comps) and dec_info" % tmax)
    # the two derived forms are written out rather than computed in the
    # assembler, so nothing depends on sdasstm8's expression parsing
    txt = (BANNER +
           "; A_MAX x T_MAX chase budget, from the Makefile variables.\n"
           "A_MAX_CFG = %d\n"
           "A_MAX_M1  = %d          ; A_MAX - 1\n"
           "A_MAX_X2  = %d          ; 2 * A_MAX (v_cand_t is u16)\n"
           "T_MAX_CFG = %d\n" % (amax, amax - 1, 2 * amax, tmax))
    p = Path(out)
    if p.is_file() and p.read_text() == txt:
        return 0
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(txt)
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    raise SystemExit(main(int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]))
